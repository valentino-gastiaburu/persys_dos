-- 1) Talla faltante en el seed: Talla_3 (tipo C)
insert into tallas (tipo, nombre, orden)
values ('C', '3', 3)
on conflict (tipo, nombre) do nothing;

-- 2) Tanda del lote de importación
insert into tandas (codigo, fecha_creacion, creado_por)
values ('INI20260905', now(), null)
on conflict (codigo) do nothing;

-- normalizacion: unificar 0706CAO y quitar prefijo 'Talla_'
drop table if exists import_norm;
create temp table import_norm as
select id, imei,
       case when imei = '0706CAO' then 'VESTIDO LARGO CAOBA' else nombre end as nombre,
       replace(talla, 'Talla_', '') as talla
from import_datos;

-- 3) Productos (uno por imei; tipo_talla segun sus tallas)
insert into productos (imei, nombre, tipo_talla, precio_referencial, estado)
select n.imei, min(n.nombre),
       case
         when array_agg(distinct tm.tipo order by tm.tipo)::text[] = array['A'] then 'A'
         when array_agg(distinct tm.tipo order by tm.tipo)::text[] = array['B'] then 'B'
         when array_agg(distinct tm.tipo order by tm.tipo)::text[] = array['C'] then 'C'
         when array_agg(distinct tm.tipo order by tm.tipo)::text[] in (array['A','B'], array['A','C']) then 'AC'
         when array_agg(distinct tm.tipo order by tm.tipo)::text[] = array['B','C'] then 'BC'
         else 'sin_talla'
       end::tipo_talla,
       0, 'activo'
from import_norm n
join tallas tm on tm.nombre = n.talla and tm.tipo in ('A','B','C')
group by n.imei
on conflict (imei) do nothing;

-- 4) Producto_Talla
insert into producto_tallas (producto_id, talla_id)
select p.id, tm.id
from import_norm n
join tallas tm on tm.nombre = n.talla and tm.tipo in ('A','B','C')
join productos p on p.imei = n.imei
group by p.id, tm.id
on conflict (producto_id, talla_id) do nothing;

-- 5) Unidades (productos_unicos) con su QR original
insert into productos_unicos (producto_id, talla_id, codigo_qr, tanda_id)
select p.id, tm.id, n.id, t.id
from import_norm n
join tallas tm on tm.nombre = n.talla and tm.tipo in ('A','B','C')
join productos p on p.imei = n.imei
join tandas t on t.codigo = 'INI20260905'
on conflict (codigo_qr) do nothing;

-- 6) Kardex: 1 entrada por (producto, talla)
insert into movimientos_stock (producto_id, talla_id, tipo, cantidad, referencia_tipo, persona_id, nota)
select p.id, tm.id, 'entrada', count(*)::int, 'ajuste', null, 'Importacion inicial 2026-09-05'
from import_norm n
join tallas tm on tm.nombre = n.talla and tm.tipo in ('A','B','C')
join productos p on p.imei = n.imei
group by p.id, tm.id
having not exists (
  select 1 from movimientos_stock m
  join productos pp on pp.id = m.producto_id
  join tallas tt on tt.id = m.talla_id
  where m.nota = 'Importacion inicial 2026-09-05'
    and pp.imei = p.imei and tt.nombre = tm.nombre
);

-- 7) Reporte
select 'unidades_importadas' as reporte, count(*) from productos_unicos where tanda_id = (select id from tandas where codigo = 'INI20260905');
select 'productos' as reporte, count(*) from productos;
select 'producto_tallas' as reporte, count(*) from producto_tallas;
select 'entradas_kardex' as reporte, count(*) from movimientos_stock where nota = 'Importacion inicial 2026-09-05';

